CREATE TABLE public.early_access_members (
  user_id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  member_number BIGINT GENERATED BY DEFAULT AS IDENTITY,
  has_seen_plus_popup BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

GRANT SELECT, INSERT, UPDATE ON public.early_access_members TO authenticated;
GRANT ALL ON public.early_access_members TO service_role;

ALTER TABLE public.early_access_members ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Users can read their own membership"
ON public.early_access_members FOR SELECT TO authenticated
USING (auth.uid() = user_id);

CREATE POLICY "Users can insert their own membership"
ON public.early_access_members FOR INSERT TO authenticated
WITH CHECK (auth.uid() = user_id);

CREATE POLICY "Users can update their own membership"
ON public.early_access_members FOR UPDATE TO authenticated
USING (auth.uid() = user_id)
WITH CHECK (auth.uid() = user_id);